BEGIN;

-- ---------------------------------------------------------------------
-- ACESSO E CADASTRO
-- ---------------------------------------------------------------------

-- US-01/02/03/25 · DA-SEG-I2-01 · DA-SEG-I3-01
-- Funcionários e pacientes que usam o sistema. "ativo = false" remove o
-- acesso de quem saiu da UBS sem apagar o histórico (US-25).
CREATE TABLE usuario (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(120) NOT NULL,
    email             VARCHAR(160) NOT NULL,
    cpf_hash          VARCHAR(64)  NOT NULL,   -- hash do CPF, usado na busca do login
    cpf_cifrado       VARCHAR(255) NOT NULL,   -- CPF cifrado, usado só para exibir
    senha_hash        VARCHAR(100) NOT NULL,   -- bcrypt; nunca a senha em texto claro
    perfil            VARCHAR(20)  NOT NULL,
    ativo             BOOLEAN      NOT NULL DEFAULT TRUE,
    tentativas_falhas INT          NOT NULL DEFAULT 0,
    bloqueado_ate     TIMESTAMPTZ,              -- nulo = conta não bloqueada
    criado_em         TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_usuario_email    UNIQUE (email),
    CONSTRAINT uk_usuario_cpf_hash UNIQUE (cpf_hash),
    CONSTRAINT ck_usuario_perfil
        CHECK (perfil IN ('PACIENTE', 'RECEPCIONISTA', 'PROFISSIONAL', 'GESTOR')),
    CONSTRAINT ck_usuario_tentativas CHECK (tentativas_falhas >= 0)
);

-- US-04/05 · US-21
-- usuario_id é nulo quando a recepção cadastra quem não usa celular (US-05);
-- cadastrado_por guarda qual recepcionista fez o cadastro.
-- Na exclusão de dados (US-21) a linha é anonimizada, não apagada, para não
-- quebrar a fila e os relatórios: por isso CPF fica nulo depois de anonimizado.
CREATE TABLE paciente (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT,
    nome            VARCHAR(120) NOT NULL,
    cpf_hash        VARCHAR(64),
    cpf_cifrado     VARCHAR(255),
    cartao_sus      VARCHAR(15),
    telefone        VARCHAR(20),
    email           VARCHAR(160),
    prioridade      VARCHAR(20)  NOT NULL DEFAULT 'NENHUMA',
    cadastrado_por  BIGINT,
    criado_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    anonimizado_em  TIMESTAMPTZ,

    CONSTRAINT fk_paciente_usuario        FOREIGN KEY (usuario_id)     REFERENCES usuario (id),
    CONSTRAINT fk_paciente_cadastrado_por FOREIGN KEY (cadastrado_por) REFERENCES usuario (id),
    CONSTRAINT uk_paciente_usuario  UNIQUE (usuario_id),
    CONSTRAINT uk_paciente_cpf_hash UNIQUE (cpf_hash),
    CONSTRAINT ck_paciente_prioridade
        CHECK (prioridade IN ('NENHUMA', 'IDOSO', 'GESTANTE', 'PCD', 'URGENCIA')),
    -- CPF é obrigatório enquanto o paciente não pediu a exclusão dos dados.
    CONSTRAINT ck_paciente_cpf
        CHECK (anonimizado_em IS NOT NULL OR (cpf_hash IS NOT NULL AND cpf_cifrado IS NOT NULL))
);

CREATE INDEX ix_paciente_cadastrado_por ON paciente (cadastrado_por);

-- US-04: versão do termo LGPD aceito e quando. Fica o histórico de aceites.
CREATE TABLE consentimento (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id  BIGINT       NOT NULL,
    versao_termo VARCHAR(20)  NOT NULL,
    aceito       BOOLEAN      NOT NULL,
    aceito_em    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_consentimento_paciente FOREIGN KEY (paciente_id) REFERENCES paciente (id)
);

CREATE INDEX ix_consentimento_paciente ON consentimento (paciente_id);

-- ---------------------------------------------------------------------
-- SERVIÇOS
-- ---------------------------------------------------------------------

-- US-06/09: clínico, enfermagem, odontologia...
CREATE TABLE servico (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(40) NOT NULL,
    ativo BOOLEAN     NOT NULL DEFAULT TRUE,

    CONSTRAINT uk_servico_nome UNIQUE (nome)
);

-- US-09: horário de funcionamento e limite de senhas por dia (1 por serviço).
CREATE TABLE configuracao_servico (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    servico_id        BIGINT NOT NULL,
    hora_abertura     TIME   NOT NULL,
    hora_fechamento   TIME   NOT NULL,
    limite_senhas_dia INT    NOT NULL,

    CONSTRAINT fk_configuracao_servico FOREIGN KEY (servico_id) REFERENCES servico (id) ON DELETE CASCADE,
    CONSTRAINT uk_configuracao_servico UNIQUE (servico_id),
    CONSTRAINT ck_configuracao_horario CHECK (hora_fechamento > hora_abertura),
    CONSTRAINT ck_configuracao_limite  CHECK (limite_senhas_dia > 0)
);

-- US-13: setor(es) de cada profissional, para ele chamar só a fila do seu serviço.
CREATE TABLE profissional_servico (
    usuario_id BIGINT NOT NULL,
    servico_id BIGINT NOT NULL,

    CONSTRAINT pk_profissional_servico PRIMARY KEY (usuario_id, servico_id),
    CONSTRAINT fk_profissional_servico_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_profissional_servico_servico FOREIGN KEY (servico_id) REFERENCES servico (id) ON DELETE CASCADE
);

CREATE INDEX ix_profissional_servico_servico ON profissional_servico (servico_id);

-- ---------------------------------------------------------------------
-- FILA E ATENDIMENTO
-- ---------------------------------------------------------------------

-- US-06/07/08/10/11/12/13 · DA-DES-I2-01
-- Status:
--   AGUARDANDO      entrou na fila, ainda não chegou à UBS
--   PRESENTE        check-in feito pela recepção (US-10)
--   CHAMADA         profissional chamou (US-13)
--   EM_ATENDIMENTO  atendimento iniciado (US-14)
--   ATENDIDA        atendimento finalizado (US-14)
--   CANCELADA       paciente cancelou (US-08)
--   FALTOSO         foi chamado e não apareceu (US-12)
-- A UNIQUE (servico_id, data_ref, numero) garante 0 senhas duplicadas mesmo
-- com entradas simultâneas: se duas transações gerarem o mesmo número, a
-- segunda falha e a aplicação tenta de novo com o próximo.
CREATE TABLE senha (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    servico_id          BIGINT      NOT NULL,
    paciente_id         BIGINT      NOT NULL,
    numero              INT         NOT NULL,
    data_ref            DATE        NOT NULL DEFAULT CURRENT_DATE,
    status              VARCHAR(20) NOT NULL DEFAULT 'AGUARDANDO',
    prioridade_aplicada VARCHAR(20) NOT NULL DEFAULT 'NENHUMA',
    prioridade_por      BIGINT,                 -- recepcionista que marcou a prioridade (US-11)
    criada_em           TIMESTAMPTZ NOT NULL DEFAULT now(),
    checkin_em          TIMESTAMPTZ,
    chamada_em          TIMESTAMPTZ,

    CONSTRAINT fk_senha_servico        FOREIGN KEY (servico_id)     REFERENCES servico (id),
    CONSTRAINT fk_senha_paciente       FOREIGN KEY (paciente_id)    REFERENCES paciente (id),
    CONSTRAINT fk_senha_prioridade_por FOREIGN KEY (prioridade_por) REFERENCES usuario (id),
    CONSTRAINT uk_senha_servico_dia_numero UNIQUE (servico_id, data_ref, numero),
    CONSTRAINT ck_senha_numero CHECK (numero > 0),
    CONSTRAINT ck_senha_status
        CHECK (status IN ('AGUARDANDO', 'PRESENTE', 'CHAMADA', 'EM_ATENDIMENTO',
                          'ATENDIDA', 'CANCELADA', 'FALTOSO')),
    CONSTRAINT ck_senha_prioridade
        CHECK (prioridade_aplicada IN ('NENHUMA', 'IDOSO', 'GESTANTE', 'PCD', 'URGENCIA')),
    -- Só pode estar chamada, em atendimento, atendida ou faltosa quem foi chamado.
    CONSTRAINT ck_senha_chamada
        CHECK (status NOT IN ('CHAMADA', 'EM_ATENDIMENTO', 'ATENDIDA', 'FALTOSO')
               OR chamada_em IS NOT NULL)
);

-- Fila do dia de um serviço (posição, próximo a chamar, painel da TV).
CREATE INDEX ix_senha_fila     ON senha (servico_id, data_ref, status);
CREATE INDEX ix_senha_paciente ON senha (paciente_id);

-- US-14/15: início, fim e observação curta, ligado ao profissional.
CREATE TABLE atendimento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    senha_id        BIGINT       NOT NULL,
    profissional_id BIGINT       NOT NULL,
    iniciado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    finalizado_em   TIMESTAMPTZ,
    observacao      VARCHAR(255),

    CONSTRAINT fk_atendimento_senha        FOREIGN KEY (senha_id)        REFERENCES senha (id),
    CONSTRAINT fk_atendimento_profissional FOREIGN KEY (profissional_id) REFERENCES usuario (id),
    CONSTRAINT uk_atendimento_senha UNIQUE (senha_id),
    CONSTRAINT ck_atendimento_periodo CHECK (finalizado_em IS NULL OR finalizado_em >= iniciado_em)
);

CREATE INDEX ix_atendimento_profissional ON atendimento (profissional_id);

-- US-23: aviso de "faltam 3 pessoas". A UNIQUE impede mandar o mesmo aviso
-- duas vezes para a mesma senha.
CREATE TABLE notificacao_email (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    senha_id   BIGINT      NOT NULL,
    tipo       VARCHAR(20) NOT NULL,
    status     VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    enviado_em TIMESTAMPTZ,                     -- preenchido quando status = ENVIADO

    CONSTRAINT fk_notificacao_senha FOREIGN KEY (senha_id) REFERENCES senha (id),
    CONSTRAINT uk_notificacao_senha_tipo UNIQUE (senha_id, tipo),
    CONSTRAINT ck_notificacao_tipo   CHECK (tipo IN ('FALTAM_3')),
    CONSTRAINT ck_notificacao_status CHECK (status IN ('PENDENTE', 'ENVIADO', 'ERRO')),
    CONSTRAINT ck_notificacao_enviado CHECK (status <> 'ENVIADO' OR enviado_em IS NOT NULL)
);

-- ---------------------------------------------------------------------
-- AUDITORIA
-- ---------------------------------------------------------------------

-- US-20: quem acessou ou alterou dados de pacientes.
-- entidade/entidade_id dizem qual registro foi tocado (ex.: 'paciente', 42).
CREATE TABLE auditoria_acesso (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL,
    paciente_id BIGINT,
    acao        VARCHAR(20)  NOT NULL,
    entidade    VARCHAR(40)  NOT NULL,
    entidade_id BIGINT       NOT NULL,
    ip_origem   VARCHAR(45),                    -- 45 cabe um IPv6
    ocorrido_em TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_auditoria_usuario  FOREIGN KEY (usuario_id)  REFERENCES usuario (id),
    CONSTRAINT fk_auditoria_paciente FOREIGN KEY (paciente_id) REFERENCES paciente (id),
    CONSTRAINT ck_auditoria_acao
        CHECK (acao IN ('CONSULTAR', 'CRIAR', 'ALTERAR', 'EXCLUIR', 'ANONIMIZAR'))
);

CREATE INDEX ix_auditoria_paciente ON auditoria_acesso (paciente_id, ocorrido_em);
CREATE INDEX ix_auditoria_usuario  ON auditoria_acesso (usuario_id, ocorrido_em);

COMMIT;
